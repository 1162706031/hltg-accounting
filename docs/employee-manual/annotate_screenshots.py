def font(size: int, *, bold: bool = False) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype(FONT_BOLD if bold else FONT_REGULAR, size=size)


def wrapped_lines(text: str, width: int) -> list[str]:
    # Chinese text has no spaces, so character wrapping is more predictable.
    chars_per_line = max(10, width // 24)
    return wrap(text, width=chars_per_line, break_long_words=True, break_on_hyphens=False)


def annotate(name: str, callouts: list[tuple[tuple[int, int], tuple[int, int, int, int], str]]) -> None:
    image = Image.open(RAW / name).convert("RGBA")
    overlay = Image.new("RGBA", image.size, (0, 0, 0, 0))
    draw = ImageDraw.Draw(overlay)
    body_font = font(21)
    number_font = font(21, bold=True)

    for number, (target, box, text) in enumerate(callouts, start=1):
        tx, ty = target
        x1, y1, box_width, box_height = box
        x2, y2 = x1 + box_width, y1 + box_height
        anchor_x = x1 if tx < x1 else x2 if tx > x2 else (x1 + x2) // 2
        anchor_y = y1 if ty < y1 else y2 if ty > y2 else (y1 + y2) // 2

        draw.line((tx, ty, anchor_x, anchor_y), fill=(220, 38, 38, 235), width=4)
        draw.rounded_rectangle((x1, y1, x2, y2), radius=12, fill=(255, 255, 255, 238), outline=(220, 38, 38, 255), width=3)
        draw.ellipse((tx - 17, ty - 17, tx + 17, ty + 17), fill=(220, 38, 38, 255), outline=(255, 255, 255, 255), width=3)
        num_text = str(number)
        num_box = draw.textbbox((0, 0), num_text, font=number_font)
        draw.text((tx - (num_box[2] - num_box[0]) / 2, ty - (num_box[3] - num_box[1]) / 2 - 2), num_text, font=number_font, fill="white")

        lines = wrapped_lines(text, x2 - x1 - 30)
        line_height = 28
        text_y = y1 + max(10, ((y2 - y1) - len(lines) * line_height) // 2)
        for line in lines:
            draw.text((x1 + 15, text_y), line, font=body_font, fill=(42, 48, 60, 255))
            text_y += line_height

    OUT.mkdir(parents=True, exist_ok=True)
    Image.alpha_composite(image, overlay).convert("RGB").save(OUT / name, quality=95)


def main() -> None:
    for name, callouts in SPECS.items():
        annotate(name, callouts)
        print(f"annotated {name}")


if __name__ == "__main__":
    main()
